--Câu 14
SELECT DISTINCT SP.MASP, SP.TENSP
FROM SANPHAM SP
LEFT JOIN CTHD CT ON SP.MASP = CT.MASP
LEFT JOIN HOADON HD ON CT.SOHD = HD.SOHD
WHERE SP.NUOCSX = 'Trung Quoc'
   OR HD.NGHD = '2007-01-01';
--Câu 15
SELECT SP.MASP, SP.TENSP
FROM SANPHAM SP
LEFT JOIN CTHD CT ON SP.MASP = CT.MASP
GROUP BY SP.MASP, SP.TENSP
HAVING COUNT(CT.MASP) = 0;
--CÂU16
SELECT SP.MASP, SP.TENSP
FROM SANPHAM SP
LEFT JOIN CTHD CT ON SP.MASP = CT.MASP
LEFT JOIN HOADON HD 
    ON CT.SOHD = HD.SOHD
    AND YEAR(HD.NGHD) = 2006
WHERE HD.SOHD IS NULL;
--CÁCH 2 CÂU 16[DÙNG NOT IN]
SELECT MASP,TENSP
FROM SANPHAM
WHERE MASP NOT IN 
	(SELECT MASP
		FROM CTHD
		LEFT JOIN HOADON ON CTHD.SOHD =HOADON.SOHD
		WHERE YEAR(NGHD)=2006)
--DÙNG NOT EXISTS
SELECT MASP,TENSP
FROM SANPHAM
WHERE NOT EXISTS
	(SELECT *
	FROM CTHD LEFT JOIN HOADON ON CTHD.SOHD = HOADON.SOHD
	WHERE YEAR(NGHD)=2006
	AND CTHD.MASP=SANPHAM.MASP

--CÂU 17
SELECT SP.MASP, SP.TENSP
FROM SANPHAM SP
LEFT JOIN CTHD CT 
    ON SP.MASP = CT.MASP
LEFT JOIN HOADON HD 
    ON CT.SOHD = HD.SOHD
    AND YEAR(HD.NGHD) = 2006
WHERE SP.NUOCSX = 'Trung Quoc'
  AND HD.SOHD IS NULL;
--CÂU 18
SELECT CT.SOHD
FROM CTHD CT
JOIN SANPHAM SP ON CT.MASP = SP.MASP
WHERE SP.NUOCSX = 'Singapore'
GROUP BY CT.SOHD
HAVING COUNT(DISTINCT CT.MASP) = 
       (SELECT COUNT(*)
        FROM SANPHAM
        WHERE NUOCSX = 'Singapore');
