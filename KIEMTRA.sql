--CÂU 1 TÌM DOANH THU BÁN HÀNG CỦA CÁC NĂM
SELECT YEAR(NGHD) AS NĂM, SUM(TRIGIA) AS Doanhthucanam
FROM HOADON
GROUP BY YEAR(NGHD)
ORDER BY NĂM
--CÂU 2 TÍNH DOANH THU BÁN HÀNG THEO THÁNG,NĂM
SELECT YEAR(NGHD) AS THÁNG, SUM(TRIGIA) AS DOANHTHUTHEOTHANG,
		MONTH(NGHD) AS NĂM
FROM HOADON
GROUP BY YEAR(NGHD),MONTH(NGHD)
ORDER BY NĂM,THÁNG
--CAU 3 HÃY LIỆT KÊ NHỮNG KHÁCH(MAKH,HOTEN) ĐÃ MUA HÀNG TRONG NĂM 2007 VÀ CÓ GIÁ TRỊ HÓA ĐƠN >=1.000.00
SELECT KH.MAKH, KH.HOTEN  
FROM KHACHHANG KH JOIN HOADON HD ON KH.MAKH = HD.MAKH
WHERE YEAR(HD.NGHD) = 2007 AND (HD.TRIGIA) >=100000
--CÂU 4. TÌM HÓA ĐƠN MUA ÍT NHÂT 3 SẢN PHẨM
SELECT SOHD, COUNT(SL) AS ítnhất3sảnphẩm
FROM CTHD
GROUP BY SOHD
HAVING COUNT(SL)>=3
